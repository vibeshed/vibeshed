import AppKit
import Foundation
import OSLog

private let log = Log.module("clipboard")

enum ClipboardManager {
    /// Token returned from `startMonitoring` to control the polling timer.
    final class MonitorToken: @unchecked Sendable {
        fileprivate var timer: Timer?
        fileprivate var lastChangeCount: Int = 0

        func invalidate() {
            timer?.invalidate()
            timer = nil
        }

        deinit {
            timer?.invalidate()
        }
    }

    /// Starts polling `NSPasteboard.general.changeCount` at the given interval.
    /// Calls `onChange` with `(content, sourceAppName)` when new string content is detected.
    @MainActor
    static func startMonitoring(
        interval: TimeInterval,
        // Not `@MainActor @Sendable`: the callback is invoked from `Timer`'s
        // nonisolated block. Annotating it would need `MainActor.assumeIsolated`
        // (a runtime trap) or a `Task` hop that loosens capture ordering.
        onChange: @escaping (String, String?) -> Void
    ) -> MonitorToken {
        let token = MonitorToken()
        token.lastChangeCount = NSPasteboard.general.changeCount

        let timer = Timer.scheduledTimer(withTimeInterval: interval, repeats: true) { _ in
            let currentCount = NSPasteboard.general.changeCount
            guard currentCount != token.lastChangeCount else { return }
            token.lastChangeCount = currentCount

            guard shouldRecord(types: NSPasteboard.general.types),
                  let content = NSPasteboard.general.string(forType: .string),
                  !content.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty
            else { return }

            let sourceApp = NSWorkspace.shared.frontmostApplication?.localizedName
            onChange(content, sourceApp)
        }
        token.timer = timer
        return token
    }

    /// Types apps put on the pasteboard to keep an item out of clipboard history
    /// (nspasteboard.org): passwords and codes from password managers, and transient
    /// or generated content.
    static let privateTypes: Set<NSPasteboard.PasteboardType> = [
        .init("org.nspasteboard.ConcealedType"),
        .init("org.nspasteboard.TransientType"),
        .init("org.nspasteboard.AutoGeneratedType"),
        .init("com.agilebits.onepassword"),
    ]

    static func shouldRecord(types: [NSPasteboard.PasteboardType]?) -> Bool {
        privateTypes.isDisjoint(with: types ?? [])
    }

    // MARK: - Pasteboard Operations

    @MainActor
    static func writeToPasteboard(_ content: String) {
        NSPasteboard.general.clearContents()
        NSPasteboard.general.setString(content, forType: .string)
    }

    /// Sends ⌘V to the app the user is in, once the picker has let go of keyboard focus
    /// (see `PickerKeyFocus`) — a ⌘V posted while it is still key pastes into its
    /// search field. Skipped if the picker keeps focus.
    @MainActor
    static func pasteFromPasteboard() async {
        let start = ContinuousClock.now
        guard await PickerKeyFocus.shared.waitUntilReleased() else {
            log.warning("Picker kept keyboard focus; skipped paste")
            return
        }
        log.debug("Pasting (waited \(start.duration(to: .now), privacy: .public) for the picker)")
        // keyCode 9 = 'v'
        guard let keyDown = CGEvent(keyboardEventSource: nil, virtualKey: 9, keyDown: true),
              let keyUp = CGEvent(keyboardEventSource: nil, virtualKey: 9, keyDown: false)
        else {
            log.error("Failed to create CGEvent for paste simulation")
            return
        }
        keyDown.flags = .maskCommand
        keyUp.flags = .maskCommand
        keyDown.post(tap: .cghidEventTap)
        keyUp.post(tap: .cghidEventTap)
    }
}
